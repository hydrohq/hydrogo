CREATE TABLE IF NOT EXISTS tenant_governance (
    tenant_id VARCHAR(128) PRIMARY KEY,
    display_name VARCHAR(255) NOT NULL DEFAULT '',
    subdomain VARCHAR(128) NOT NULL DEFAULT '',
    custom_domain VARCHAR(255) NOT NULL DEFAULT '',
    blueprint VARCHAR(64) NOT NULL DEFAULT 'boutique',
    plan VARCHAR(64) NOT NULL DEFAULT 'starter',
    lifecycle_state VARCHAR(32) NOT NULL DEFAULT 'active' CHECK (lifecycle_state IN ('provisioning', 'active', 'readonly', 'suspended', 'archived')),
    trial_ends_at VARCHAR(64) NOT NULL DEFAULT '',
    subscription_ends_at VARCHAR(64) NOT NULL DEFAULT '',
    max_storage_bytes BIGINT NOT NULL DEFAULT 536870912,
    max_records INT NOT NULL DEFAULT 5000,
    rate_limit_rps INT NOT NULL DEFAULT 30,
    max_concurrent_reqs INT NOT NULL DEFAULT 15,
    max_upload_bytes BIGINT NOT NULL DEFAULT 10485760,
    ai_enabled TINYINT(1) NOT NULL DEFAULT 1,
    ai_provider VARCHAR(64) NOT NULL DEFAULT 'gemini',
    ai_model VARCHAR(128) NOT NULL DEFAULT 'gemini-2.5-flash',
    ai_encrypted_api_key TEXT,
    ai_monthly_token_limit BIGINT NOT NULL DEFAULT 500000,
    ai_tokens_used BIGINT NOT NULL DEFAULT 0,
    owner_phone VARCHAR(64) NOT NULL DEFAULT '',
    notes TEXT,
    created_at DATETIME(6) NOT NULL,
    updated_at DATETIME(6) NOT NULL,
    INDEX idx_tenant_governance_subdomain (subdomain),
    INDEX idx_tenant_governance_custom_domain (custom_domain)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
