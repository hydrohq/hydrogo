// Command baselinegen regenerates the schema baseline under migrations/baseline
// (ADR 0009) from the migration chain. It builds each module set on a throwaway
// database per dialect, so it needs a PostgreSQL and a MySQL 8 server account
// that may create databases:
//
//	HYDRO_BASELINE_POSTGRES_URL=postgres://user:pass@127.0.0.1:5432/postgres?sslmode=disable \
//	HYDRO_BASELINE_MYSQL_URL='root@tcp(127.0.0.1:3306)/mysql?parseTime=true' \
//	  go run ./tools/baselinegen
//
// A baseline is immutable once released, like a migration: run this only when
// the baseline is being introduced or deliberately replaced.
package main

import (
	"context"
	"crypto/sha256"
	"encoding/hex"
	"flag"
	"fmt"
	"os"
	"path/filepath"
	"strings"

	"github.com/ardaozyildirim/hydrogo/internal/database"
	"github.com/ardaozyildirim/hydrogo/internal/database/baselinegen"
	"github.com/ardaozyildirim/hydrogo/migrations"
	"gopkg.in/yaml.v3"
)

type manifestGroup struct {
	ID         string            `yaml:"id"`
	Modules    []string          `yaml:"modules"`
	Migrations []string          `yaml:"migrations"`
	Checksums  map[string]string `yaml:"checksums"`
}

type manifest struct {
	Version int             `yaml:"version"`
	Groups  []manifestGroup `yaml:"groups"`
}

func main() {
	out := flag.String("out", "migrations/baseline", "baseline directory")
	dialects := flag.String("dialects", "sqlite,postgres,mysql", "comma-separated dialects to generate")
	chainOnly := flag.String("chain-only", "", "comma-separated groups whose migrations stay in the chain instead of the baseline")
	flag.Parse()
	if err := run(context.Background(), *out, strings.Split(*dialects, ","), strings.Split(*chainOnly, ",")); err != nil {
		fmt.Fprintln(os.Stderr, "baselinegen:", err)
		os.Exit(1)
	}
}

func dsn(name string) string {
	if value := os.Getenv("HYDRO_BASELINE_" + name + "_URL"); value != "" {
		return value
	}
	return os.Getenv("HYDRO_TEST_" + name + "_URL")
}

func run(ctx context.Context, out string, dialects, chainOnly []string) error {
	all, err := baselinegen.Groups(migrations.FS)
	if err != nil {
		return err
	}
	groups := baselinegen.Covered(all, chainOnly)
	if err := os.MkdirAll(out, 0o750); err != nil {
		return err
	}
	// Writes and reads stay inside the baseline directory, whatever a group
	// or dialect name contains.
	root, err := os.OpenRoot(out)
	if err != nil {
		return err
	}
	defer root.Close()
	for _, name := range dialects {
		dialect := database.Dialect(strings.TrimSpace(name))
		var admin string
		switch dialect {
		case database.Postgres:
			admin = dsn("POSTGRES")
		case database.MySQL:
			admin = dsn("MYSQL")
		}
		provider, err := baselinegen.NewProvider(dialect, admin, "")
		if err != nil {
			return fmt.Errorf("%s: %w", dialect, err)
		}
		generated, err := baselinegen.Generate(ctx, provider, migrations.FS, chainOnly)
		if err != nil {
			return fmt.Errorf("%s: %w", dialect, err)
		}
		for _, group := range generated {
			if err := root.MkdirAll(group.ID, 0o750); err != nil {
				return err
			}
			if err := root.WriteFile(filepath.Join(group.ID, string(dialect)+".sql"), []byte(group.Script), 0o600); err != nil {
				return err
			}
		}
		fmt.Printf("baselinegen: %s: %d groups\n", dialect, len(generated))
	}
	m := manifest{Version: 1}
	for _, group := range groups {
		entry := manifestGroup{ID: group.ID, Modules: group.Modules, Migrations: group.Migrations, Checksums: map[string]string{}}
		if entry.Modules == nil {
			entry.Modules = []string{}
		}
		for _, dialect := range []database.Dialect{database.SQLite, database.Postgres, database.MySQL} {
			content, err := root.ReadFile(filepath.Join(group.ID, string(dialect)+".sql"))
			if os.IsNotExist(err) {
				continue
			}
			if err != nil {
				return err
			}
			sum := sha256.Sum256(content)
			entry.Checksums[string(dialect)] = hex.EncodeToString(sum[:])
		}
		m.Groups = append(m.Groups, entry)
	}
	data, err := yaml.Marshal(m)
	if err != nil {
		return err
	}
	header := "# Generated by tools/baselinegen from the migration chain; do not edit.\n# See docs/decisions/0009-core-owned-event-outbox-and-migration-baseline.md.\n"
	return root.WriteFile("manifest.yml", append([]byte(header), data...), 0o600)
}
