// Package aurora provides the "Aurora" admin Studio visual family: a fifth,
// additive dashboard rendering authored with real Tailwind utility classes
// (compiled by the standalone Tailwind CLI, ADR-0338's toolchain) instead of
// the ADR-0053 semantic token contract the other four families share. See
// docs/archive/architecture/0339-tailwind-admin-visual-family.md for the full
// rationale, including why the compiled stylesheet is safe to load alongside
// AdminCSS (Tailwind's preflight layer is excluded and both the utility
// classes and the generated theme CSS variables are namespaced under the
// "tw:" / "--tw-" prefix, so nothing here can collide with or override an
// ADR-0053 semantic token name).
package aurora

import (
	"embed"
	"html/template"
)

//go:embed dist/aurora.css
var cssFS embed.FS

//go:embed dashboard.tmpl.html
var markupFS embed.FS

// CSSText is the compiled, Tailwind-prefixed stylesheet for the Aurora
// dashboard, concatenated into the shared admin stylesheet
// (internal/ui/admin_shell.go) alongside AdminCSS. It is regenerated by
// scripts/build-aurora-tailwind.ps1 whenever dashboard.tmpl.html's classes
// change.
var CSSText = mustReadCSS()

func mustReadCSS() string {
	b, err := cssFS.ReadFile("dist/aurora.css")
	if err != nil {
		panic(err)
	}
	return string(b)
}

// DashboardTemplate renders the Aurora dashboard body. It is executed with
// the same ui.AdminDashboardData value as the other four families' dashboard
// templates (internal/ui/admin_workbench.go, internal/ui/admin_nova_dashboard.go).
var DashboardTemplate = template.Must(template.New("aurora-dashboard").Parse(mustReadMarkup()))

func mustReadMarkup() string {
	b, err := markupFS.ReadFile("dashboard.tmpl.html")
	if err != nil {
		panic(err)
	}
	return string(b)
}
