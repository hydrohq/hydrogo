// Package hydrogoui provides the "hydrogo" admin Studio visual family's own
// flagship dashboard body (ADR-0341), authored with real Tailwind utility
// classes and compiled with the standalone Tailwind CLI (ADR-0338's
// toolchain). hydrogo is Studio's only visual family: its chrome
// (sidebar/topbar) restyle lives in internal/ui/admin_hydrogo.go
// (AdminHydroGoCSS, applied to the shared markup via plain CSS); only the
// dashboard body is its own isolated markup here, genuinely restructured
// (icon-badge stat cards, a collections grid, a system-status card, and a
// quick-actions panel) rather than a reskin of the old shared wb-* dashboard
// layout.
package hydrogoui

import (
	"embed"
	"html/template"
)

//go:embed dist/hydrogo.css
var cssFS embed.FS

//go:embed dashboard.tmpl.html
var markupFS embed.FS

// CSSText is the compiled, Tailwind-prefixed stylesheet for the hydrogo
// dashboard, concatenated into the shared admin stylesheet
// (internal/ui/admin_shell.go) alongside AdminCSS. It is regenerated by
// scripts/build-hydrogoui-tailwind.ps1 whenever dashboard.tmpl.html's
// classes change.
var CSSText = mustReadCSS()

func mustReadCSS() string {
	b, err := cssFS.ReadFile("dist/hydrogo.css")
	if err != nil {
		panic(err)
	}
	return string(b)
}

// DashboardTemplate renders the hydrogo dashboard body. It is executed with
// the same ui.AdminDashboardData value as the other families' dashboard
// templates.
var DashboardTemplate = template.Must(template.New("hydrogo-dashboard").Parse(mustReadMarkup()))

func mustReadMarkup() string {
	b, err := markupFS.ReadFile("dashboard.tmpl.html")
	if err != nil {
		panic(err)
	}
	return string(b)
}
