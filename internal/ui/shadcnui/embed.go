// Package shadcnui provides the "shadcn" admin Studio visual family's own
// dashboard body, authored with real shadcn/ui component conventions (the
// card recipe "rounded-xl border bg-card text-card-foreground shadow-sm",
// a data table, badges, and button variants) and compiled with the
// standalone Tailwind CLI (ADR-0338's toolchain), the same pattern
// internal/ui/aurora already established. See
// docs/architecture/0341-admin-family-overhaul.md for the full rationale:
// shadcn previously only reused the shared wb-*/dashboard-* markup restyled
// with shadcn's color tokens, which never actually looked like shadcn/ui's
// component system. The chrome (sidebar/topbar) stays on the shared markup,
// restyled via @apply in internal/ui/admin_shadcn.go - only the dashboard
// body gets its own isolated markup here, matching Aurora's precedent.
package shadcnui

import (
	"embed"
	"html/template"
)

//go:embed dist/shadcn.css
var cssFS embed.FS

//go:embed dashboard.tmpl.html
var markupFS embed.FS

// CSSText is the compiled, Tailwind-prefixed stylesheet for the shadcn
// dashboard, concatenated into the shared admin stylesheet
// (internal/ui/admin_shell.go) alongside AdminCSS. It is regenerated by
// scripts/build-shadcnui-tailwind.ps1 whenever dashboard.tmpl.html's classes
// change.
var CSSText = mustReadCSS()

func mustReadCSS() string {
	b, err := cssFS.ReadFile("dist/shadcn.css")
	if err != nil {
		panic(err)
	}
	return string(b)
}

// DashboardTemplate renders the shadcn dashboard body. It is executed with
// the same ui.AdminDashboardData value as the other families' dashboard
// templates.
var DashboardTemplate = template.Must(template.New("shadcn-dashboard").Parse(mustReadMarkup()))

func mustReadMarkup() string {
	b, err := markupFS.ReadFile("dashboard.tmpl.html")
	if err != nil {
		panic(err)
	}
	return string(b)
}
