package generator

import (
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"sort"
	"strconv"
	"strings"

	"github.com/ardaozyildirim/hydrogo/internal/pathguard"
)

type generatedRouteResource struct {
	ID           string
	Name         string
	TenantScoped bool
}

func updateGeneratedRouteRegistration(root, generatedRoot string) error {
	path := filepath.Join(generatedRoot, "route_registration.go")
	packagePath, found, err := generatedPackageImportPath(root)
	if err != nil {
		return err
	}
	if !found {
		info, err := os.Lstat(path)
		if os.IsNotExist(err) {
			return nil
		}
		if err != nil {
			return err
		}
		if info.Mode()&os.ModeSymlink != 0 || !info.Mode().IsRegular() {
			return fmt.Errorf("generated route registration is not a regular file")
		}
		return os.Remove(path)
	}
	resources, err := generatedRouteResources(generatedRoot)
	if err != nil {
		return err
	}
	source, err := renderGeneratedRouteRegistration(packagePath, resources)
	if err != nil {
		return err
	}
	return writeGenerated(path, source)
}

func generatedPackageImportPath(root string) (string, bool, error) {
	absRoot, err := filepath.Abs(root)
	if err != nil {
		return "", false, err
	}
	for dir := absRoot; ; dir = filepath.Dir(dir) {
		goMod, err := os.ReadFile(filepath.Join(dir, "go.mod"))
		if err == nil {
			modulePath := ""
			for _, line := range strings.Split(string(goMod), "\n") {
				fields := strings.Fields(line)
				if len(fields) >= 2 && fields[0] == "module" {
					modulePath = strings.Trim(fields[1], `"`)
					break
				}
			}
			if modulePath == "" || strings.ContainsAny(modulePath, "\\ \t\r\n") {
				return "", false, fmt.Errorf("invalid module path in %s", filepath.Join(dir, "go.mod"))
			}
			rel, err := filepath.Rel(dir, absRoot)
			if err != nil || rel == ".." || strings.HasPrefix(rel, ".."+string(filepath.Separator)) {
				return "", false, fmt.Errorf("generator root is outside module root")
			}
			if rel == "." {
				return strings.TrimSuffix(modulePath, "/") + "/generated", true, nil
			}
			return strings.TrimSuffix(modulePath, "/") + "/" + filepath.ToSlash(rel) + "/generated", true, nil
		}
		if !os.IsNotExist(err) {
			return "", false, err
		}
		parent := filepath.Dir(dir)
		if parent == dir {
			return "", false, nil
		}
	}
}

func generatedRouteResources(generatedRoot string) ([]generatedRouteResource, error) {
	entries, err := os.ReadDir(generatedRoot)
	if err != nil {
		return nil, err
	}
	resources := make([]generatedRouteResource, 0, len(entries))
	for _, entry := range entries {
		if !entry.IsDir() {
			continue
		}
		resourceRoot := filepath.Join(generatedRoot, entry.Name())
		if err := pathguard.RejectSymlinkComponents(resourceRoot); err != nil {
			return nil, fmt.Errorf("generated resource %s: %w", entry.Name(), err)
		}
		spec, err := LoadSpec(filepath.Join(resourceRoot, "spec.json"))
		if err != nil {
			return nil, fmt.Errorf("load generated resource %s: %w", entry.Name(), err)
		}
		resources = append(resources, generatedRouteResource{ID: spec.Name, Name: exportName(spec.Name), TenantScoped: spec.TenantScoped})
	}
	sort.Slice(resources, func(i, j int) bool { return resources[i].ID < resources[j].ID })
	if len(resources) == 0 {
		return nil, fmt.Errorf("generated root contains no resources")
	}
	return resources, nil
}

func renderGeneratedRouteRegistration(packagePath string, resources []generatedRouteResource) ([]byte, error) {
	var imports strings.Builder
	var prepare strings.Builder
	var registrations strings.Builder
	for i, resource := range resources {
		alias := fmt.Sprintf("resource%d", i)
		fmt.Fprintf(&imports, "\t%s %s\n", alias, strconv.Quote(packagePath+"/"+resource.ID))
		fmt.Fprintf(&prepare, `	policy%d := options.PolicyFor(%q)
		if policy%d == nil { return fmt.Errorf("generated resource %%s has no policy", %q) }
`, i, resource.ID, i, resource.ID)
		if resource.TenantScoped {
			fmt.Fprintf(&prepare, `	if options.ResolveTenant == nil { return fmt.Errorf("generated tenant resource %%s has no tenant resolver", %q) }
		resolver%d := func(r *http.Request) (string, bool) { return options.ResolveTenant(%q, r) }
`, resource.ID, i, resource.ID)
			fmt.Fprintf(&registrations, `	if err := %s.Register%sRoute(mux, options.DB, options.Dialect, policy%d, resolver%d); err != nil { return err }
`, alias, resource.Name, i, i)
		} else {
			fmt.Fprintf(&registrations, `	if err := %s.Register%sRoute(mux, options.DB, options.Dialect, policy%d); err != nil { return err }
`, alias, resource.Name, i)
		}
	}
	source := fmt.Sprintf(`// Code generated by hydrogo generator; DO NOT EDIT.
package generated

import (
	"context"
	"database/sql"
	"errors"
	"fmt"
	"net/http"
%s)

// GeneratedResourcePolicy is the shared authorization shape required by
// generated collection APIs. The Edition still decides each grant.
type GeneratedResourcePolicy interface {
	CanRead(context.Context, string) bool
	CanCreate(context.Context) bool
	CanUpdate(context.Context, string) bool
	CanDelete(context.Context, string) bool
}

// GeneratedResourceOptions carries Edition-owned dependencies for the full
// generated resource set. Tenant resolvers are called only for tenant resources.
type GeneratedResourceOptions struct {
	DB *sql.DB
	Dialect string
	PolicyFor func(string) GeneratedResourcePolicy
	ResolveTenant func(string, *http.Request) (string, bool)
}

// RegisterGeneratedResources explicitly activates all generated resource API
// routes. Callers needing a subset can continue to register resource routes
// individually. No migration, middleware, policy, or worker is inferred.
func RegisterGeneratedResources(mux *http.ServeMux, options GeneratedResourceOptions) error {
	if mux == nil || options.DB == nil || options.PolicyFor == nil {
		return errors.New("generated resource registration requires mux, database and policy resolver")
	}
%s
%s	return nil
}
`, imports.String(), prepare.String(), registrations.String())
	return format.Source([]byte(source))
}
