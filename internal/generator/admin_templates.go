type adminTemplateField struct {
	Name               string
	Label              string
	Widget             string
	InputType          string
	Required           bool
	Boolean            bool
	Options            []string
	RelationCollection string
}

type adminTemplateData struct {
	Name         string
	Title        string
	Route        string
	Fields       []adminTemplateField
	ListFields   []adminTemplateField
	SearchFields []adminTemplateField
	FilterFields []adminTemplateField
}

func newAdminTemplateData(spec Spec) adminTemplateData {
	fields := append([]Field(nil), spec.Fields...)
	sort.Slice(fields, func(i, j int) bool { return fields[i].Name < fields[j].Name })
	data := adminTemplateData{Name: exportName(spec.Name), Title: strings.TrimSpace(spec.Admin.Label), Route: "/admin/" + spec.Name}
	if data.Title == "" {
		data.Title = exportName(spec.Name)
	}
	for _, field := range fields {
		label := strings.TrimSpace(field.Admin.Label)
		if label == "" {
			label = exportName(field.Name)
		}
		widget := strings.ToLower(strings.TrimSpace(field.Admin.Widget))
		inputType := "text"
		switch strings.ToLower(field.Type) {
		case "int", "integer", "number", "real", "float":
			inputType = "number"
		case "bool", "boolean":
			inputType = "checkbox"
		case "date":
			inputType = "date"
		case "datetime", "timestamp":
			inputType = "datetime-local"
		}
		relationCollection := ""
		if field.Relation != nil {
			relationCollection = field.Relation.Collection
		}
		item := adminTemplateField{Name: field.Name, Label: label, Widget: widget, InputType: inputType, Required: !field.Nullable, Boolean: inputType == "checkbox", Options: append([]string(nil), field.Admin.Options...), RelationCollection: relationCollection}
		data.Fields = append(data.Fields, item)
		if field.Admin.VisibleInList {
			data.ListFields = append(data.ListFields, item)
		}
		if field.Admin.Searchable {
			data.SearchFields = append(data.SearchFields, item)
		}
		if field.Admin.Filterable {
			data.FilterFields = append(data.FilterFields, item)
		}
	}
	return data
}

