// Package testgen turns content-type definitions into Playwright specs that
// prove every admin role gets exactly the read/write access its declared
// permissions say it should. It targets a project created by `hydro new`,
// which has no Go module of its own (see internal/scaffold) — so every
// generated test is a black-box HTTP check against a running `hydro serve`,
// never an in-process call into HydroGo's own packages.
//
// Scope, on purpose: this generates the access-control matrix (who can list,
// who can create), not full business-flow QA. Verifying that a create
// actually saves valid business data (a real company id, a real deal amount,
// ...) needs domain knowledge the schema alone doesn't carry; those journeys
// belong hand-written in e2e/custom/. What this package generates needs no
// seeded data and no knowledge of the content type's business rules, which
// is what keeps it safe to regenerate on every schema change.
package testgen

import (
	"fmt"
	"sort"
	"strings"

	"github.com/hydrohq/hydrogo/internal/contenttypes"
)

// File is one generated file, with Path relative to the output directory
// (e.g. "content/deals.spec.ts").
type File struct {
	Path    string
	Content string
}

const generatedHeader = "// Code generated by `hydro generate tests` — DO NOT EDIT.\n"

// builtinRoles are the roles every HydroGo installation has; see
// internal/auth.Role. A role with an explicit permission override can also
// pass a custom permission check, but seeding one isn't part of this
// generator yet — see the package doc.
var builtinRoles = []string{"admin", "editor", "viewer"}

// Generate returns one spec per definition plus the shared login helper,
// sorted by content type id so the output is deterministic across runs.
func Generate(definitions []contenttypes.Definition) []File {
	sorted := append([]contenttypes.Definition(nil), definitions...)
	sort.Slice(sorted, func(i, j int) bool { return sorted[i].ID < sorted[j].ID })

	files := []File{{Path: "content/_helpers.ts", Content: helpersFile}}
	for _, definition := range sorted {
		files = append(files, File{
			Path:    fmt.Sprintf("content/%s.spec.ts", definition.ID),
			Content: generateSpec(definition),
		})
		if spec := generatePublicSpec(definition); spec != "" {
			files = append(files, File{Path: fmt.Sprintf("content/%s.public.spec.ts", definition.ID), Content: spec})
		}
	}
	return files
}

func generateSpec(d contenttypes.Definition) string {
	var b strings.Builder
	b.WriteString(generatedHeader)
	fmt.Fprintf(&b, "// Source: content-types/%s.yaml (or its preset subdirectory).\n", d.ID)
	b.WriteString(`import { test, expect } from "@playwright/test";` + "\n")
	b.WriteString(`import { login, mutHeaders } from "./_helpers";` + "\n\n")
	fmt.Fprintf(&b, "const PATH = \"/api/v1/admin/content/%s\";\n\n", d.ID)
	fmt.Fprintf(&b, "test.describe(%q, () => {\n", d.ID+" — role access")

	writeReadTests(&b, d)
	writeWriteTests(&b, d)

	b.WriteString("});\n")
	return b.String()
}

func writeReadTests(b *strings.Builder, d contenttypes.Definition) {
	custom := d.Permissions.Read != ""
	for _, role := range builtinRoles {
		allowed := !custom || role == "admin"
		fmt.Fprintf(b, "  test(%q, async () => {\n", fmt.Sprintf("%s can%s read", role, negate(allowed)))
		fmt.Fprintf(b, "    const session = await login(%q);\n", role)
		b.WriteString("    const res = await session.ctx.get(PATH);\n")
		if allowed {
			if custom {
				b.WriteString("    // Custom read permission: only admin (or an explicit grant, not seeded by hydro seed-test-users) passes.\n")
			}
			b.WriteString("    expect(res.status()).toBe(200);\n")
		} else {
			fmt.Fprintf(b, "    // content-types/%s declares permissions.read: %q; %s lacks it and no seeded account has an override.\n", d.ID, d.Permissions.Read, role)
			b.WriteString("    expect(res.status()).toBe(403);\n")
		}
		b.WriteString("  });\n\n")
	}
}

func writeWriteTests(b *strings.Builder, d contenttypes.Definition) {
	custom := d.Permissions.Write != ""
	for _, role := range builtinRoles {
		allowed := roleHasGenericWrite(role) && (!custom || role == "admin")
		fmt.Fprintf(b, "  test(%q, async () => {\n", fmt.Sprintf("%s can%s create", role, negate(allowed)))
		fmt.Fprintf(b, "    const session = await login(%q);\n", role)
		b.WriteString("    const res = await session.ctx.post(PATH, { headers: mutHeaders(session), data: {} });\n")
		if allowed {
			b.WriteString("    // An empty body may fail validation (422) — this only asserts access was granted, not that the record is valid;\n")
			b.WriteString("    // a full valid-payload create belongs in e2e/custom/, where the content type's business rules are known.\n")
			b.WriteString("    expect(res.status()).not.toBe(403);\n")
		} else {
			if custom {
				fmt.Fprintf(b, "    // This type declares a custom write permission — content-types/%s has permissions.write: %q; %s lacks it.\n", d.ID, d.Permissions.Write, role)
			} else {
				fmt.Fprintf(b, "    // %s has read-only access by default (no admin.content.write).\n", role)
			}
			b.WriteString("    expect(res.status()).toBe(403);\n")
		}
		b.WriteString("  });\n\n")
	}
}

// roleHasGenericWrite mirrors internal/auth's fixed role hierarchy for the
// generic admin.content.write permission (viewer never gets it).
func roleHasGenericWrite(role string) bool {
	return role == "admin" || role == "editor"
}

func negate(allowed bool) string {
	if allowed {
		return ""
	}
	return "not"
}

const helpersFile = generatedHeader + `
import { request as pwRequest, type APIRequestContext } from "@playwright/test";
import { readFileSync } from "node:fs";

export type Role = "admin" | "editor" | "viewer";

const BASE_URL = process.env.HYDRO_E2E_BASE_URL ?? "http://127.0.0.1:8080";

export interface Session {
  ctx: APIRequestContext;
  csrfToken: string;
}

/**
 * Reuses the session ../global-setup.ts logged in once for this role,
 * instead of logging in again per test: HydroGo's own login rate limit
 * (5/minute per IP, shared across every role) is easy to trip the moment
 * more than a handful of generated tests run in parallel, and it's the
 * same limit a real brute-force attempt would hit — so the fix is fewer
 * logins, not a higher limit.
 */
export async function login(role: Role): Promise<Session> {
  let csrfToken: string;
  try {
    csrfToken = readFileSync(` + "`.auth/${role}.csrf`" + `, "utf8").trim();
  } catch {
    throw new Error(
      ` + "`.auth/${role}.csrf is missing — did global-setup.ts run? It needs HYDRO_E2E_${role.toUpperCase()}_EMAIL/PASSWORD (run: hydro seed-test-users).`" + `
    );
  }
  const ctx = await pwRequest.newContext({ baseURL: BASE_URL, storageState: ` + "`.auth/${role}.json`" + ` });
  return { ctx, csrfToken };
}

/** Headers a non-GET request needs on top of the session's cookies. */
export function mutHeaders(session: Session): Record<string, string> {
  return { "x-csrf-token": session.csrfToken };
}

/** A signed-out visitor: no login, only the CSRF cookie + token a public write needs. */
export async function anonymous(): Promise<Session> {
  const ctx = await pwRequest.newContext({ baseURL: BASE_URL });
  const res = await ctx.get("/csrf-token");
  const { token } = (await res.json()) as { token: string };
  return { ctx, csrfToken: token };
}
`

// generatePublicSpec writes the public-API safety checks for a public type: a
// private field must never come back to a visitor (nor be sortable), and a
// drafts type must never let a visitor publish their own record. Both are
// properties of the schema alone, so they are safe to regenerate. Returns ""
// when the type has nothing of the kind to check.
func generatePublicSpec(d contenttypes.Definition) string {
	if !d.Public {
		return ""
	}
	var private []string
	for _, f := range d.Fields {
		if f.Private {
			private = append(private, f.ID)
		}
	}
	payload, marker, canCreate := samplePayload(d)
	checkDrafts := d.Drafts && canCreate
	if len(private) == 0 && !checkDrafts {
		return ""
	}

	var b strings.Builder
	b.WriteString(generatedHeader)
	fmt.Fprintf(&b, "// Source: content-types/%s.yaml. Public-API safety checks derived from the schema.\n", d.ID)
	b.WriteString(`import { test, expect } from "@playwright/test";` + "\n")
	b.WriteString(`import { anonymous, mutHeaders } from "./_helpers";` + "\n\n")
	fmt.Fprintf(&b, "const PUBLIC = \"/api/v1/content/%s\";\n\n", d.ID)
	fmt.Fprintf(&b, "test.describe(%q, () => {\n", d.ID+" — public API safety")

	for _, field := range private {
		fmt.Fprintf(&b, "  test(%q, async () => {\n", "private field "+field+" never reaches a visitor")
		b.WriteString("    const visitor = await anonymous();\n")
		b.WriteString("    const res = await visitor.ctx.get(PUBLIC);\n")
		b.WriteString("    // A type whose public list is closed answers 401/403/404: nothing to leak either way.\n")
		b.WriteString("    if (res.status() !== 200) return;\n")
		b.WriteString("    const body = (await res.json()) as { data?: Record<string, unknown>[] };\n")
		fmt.Fprintf(&b, "    for (const item of body.data ?? []) expect(item).not.toHaveProperty(%q);\n", field)
		fmt.Fprintf(&b, "    const sorted = await visitor.ctx.get(PUBLIC + %q);\n", "?sort="+field)
		b.WriteString("    expect(sorted.status()).not.toBe(200);\n")
		b.WriteString("  });\n\n")
	}

	if checkDrafts {
		b.WriteString("  test(\"a visitor cannot publish their own record\", async () => {\n")
		b.WriteString("    const visitor = await anonymous();\n")
		fmt.Fprintf(&b, "    const res = await visitor.ctx.post(PUBLIC, { headers: mutHeaders(visitor), data: %s });\n", payload)
		b.WriteString("    // Closed to visitors (401/403) or rejected (4xx): fine, nothing was published.\n")
		b.WriteString("    if (res.status() !== 201) return;\n")
		b.WriteString("    const created = (await res.json()) as { data?: { status?: string } };\n")
		b.WriteString("    expect(created.data?.status ?? \"draft\").toBe(\"draft\");\n")
		b.WriteString("    const list = await visitor.ctx.get(PUBLIC);\n")
		b.WriteString("    if (list.status() !== 200) return;\n")
		fmt.Fprintf(&b, "    expect(JSON.stringify(await list.json())).not.toContain(%q);\n", marker)
		b.WriteString("  });\n")
	}
	b.WriteString("});\n")
	return b.String()
}

// samplePayload builds a minimal valid body from the required fields when all
// of them are simple kinds. The first text field carries a marker so the test
// can recognise its own record. ok=false when a required field (a relation,
// media, ...) needs data the schema cannot invent.
func samplePayload(d contenttypes.Definition) (payload, marker string, ok bool) {
	const markerValue = "e2e-public-safety-marker"
	parts := []string{`"status": "published"`}
	marked := false
	for _, f := range d.Fields {
		if !f.Required {
			continue
		}
		var v string
		switch f.Kind {
		case "text", "textarea", "richtext":
			v = fmt.Sprintf("%q", markerValue)
			marked = true
		case "number":
			v = "1"
			if f.Min != nil {
				v = fmt.Sprintf("%v", *f.Min)
			}
		case "boolean":
			v = "true"
		case "select":
			if len(f.Options) == 0 {
				return "", "", false
			}
			v = fmt.Sprintf("%q", f.Options[0])
		case "date":
			v = `"2026-01-01"`
		case "datetime":
			v = `"2026-01-01T00:00:00Z"`
		default:
			return "", "", false
		}
		parts = append(parts, fmt.Sprintf("%q: %s", f.ID, v))
	}
	if !marked {
		return "", "", false
	}
	return "{ " + strings.Join(parts, ", ") + " }", markerValue, true
}
